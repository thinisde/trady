#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MarketSession {
    pub session_id: String,
    pub opens_at: DateTime<Utc>,
    pub closes_at: DateTime<Utc>,
    pub observed_at: DateTime<Utc>,
    pub opening_equity: Money,
    pub deposits: Money,
    pub withdrawals: Money,
}
impl MarketSession {
    fn validate(&self, currency: &Currency, now: DateTime<Utc>) -> Result<()> {
        require(
            !self.session_id.is_empty()
                && self.opens_at < self.closes_at
                && now >= self.opens_at
                && now < self.closes_at
                && fresh(self.observed_at, now, 60),
            "missing, stale or inactive exchange session",
        )?;
        require(
            self.opening_equity.currency == *currency
                && self.deposits.currency == *currency
                && self.withdrawals.currency == *currency
                && self.opening_equity.amount > Decimal::ZERO
                && self.deposits.amount >= Decimal::ZERO
                && self.withdrawals.amount >= Decimal::ZERO,
            "invalid session accounting",
        )
    }
    fn permits_entry(&self, now: DateTime<Utc>) -> bool {
        ExchangeSession {
            session_id: self.session_id.clone(),
            opens_at: self.opens_at,
            closes_at: self.closes_at,
        }
        .permits_entry(now)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ExecutionObservation {
    pub snapshot: AccountSnapshot,
    /// Actual remaining acquisition cost in account currency, including broker-reported costs.
    pub position_costs: BTreeMap<InstrumentId, Money>,
    /// A submitted protective sell may reserve stock. Never sell more than this quantity.
    pub available_quantities: BTreeMap<InstrumentId, Decimal>,
    pub total_equity: Money,
}

pub trait ExecutionBroker: BrokerExecutionPort {
    /// Must include pending orders AND terminal history for the exact tracked broker IDs.
    /// Absence is uncertainty, never evidence that a mutation failed.
    fn observe(
        &mut self,
        account: &AccountId,
        tracked: &[TrackedOrder],
    ) -> Result<ExecutionObservation>;
    /// Adapters with pacing or additional reads must check this expiry immediately
    /// before dispatch. Immediate fixture ports may use the default implementation.
    fn submit_order_before(
        &mut self,
        request: &BrokerOrderRequest,
        _expires_at: DateTime<Utc>,
    ) -> BrokerResult<BrokerOrder> {
        self.submit_order(request)
    }
}

pub trait TradingInputs {
    fn session(&mut self, account: &AccountId, now: DateTime<Utc>)
    -> Result<Option<MarketSession>>;
    fn quote(&mut self, instrument: &InstrumentId) -> Result<Quote>;
    /// Trusted analyst boundary: resolve evidence; run automatic screening and native inference.
    /// The executor independently validates its returned dossier, bindings and calculations.
    fn candidate(
        &mut self,
        snapshot: &AccountSnapshot,
        now: DateTime<Utc>,
    ) -> Result<Option<EntryCandidate>>;
    fn current_exit_costs(
        &mut self,
        _instrument: &InstrumentId,
        _now: DateTime<Utc>,
    ) -> Result<Option<trady_policy::EntryCosts>> {
        Ok(None)
    }
}

pub trait ExecutionJournal {
    fn acquire(
        &mut self,
        config: &TradingConfig,
        worker: &WorkerId,
        ttl_seconds: i32,
    ) -> Result<Fence>;
    fn renew(&mut self, fence: &Fence, ttl_seconds: i32) -> Result<()>;
    fn load(&mut self, fence: &Fence) -> Result<TradingState>;
    /// Atomic fenced compare-and-swap. Persist before dispatching ANY mutation.
    fn save(&mut self, fence: &Fence, expected_revision: u64, state: &TradingState) -> Result<()>;
    /// Publish broker-observed holding economics through the executor's fence.
    /// Read-only analyst repositories cannot create this attestation.
    fn record_holding_observation(
        &mut self,
        _fence: &Fence,
        _observation: &ExecutionObservation,
        _exit_costs: &trady_policy::EntryCosts,
    ) -> Result<()> {
        Ok(())
    }
    /// Only a trusted, persisted analyst review may be returned. Models cannot
    /// write directly to this queue or bypass current executor observations.
    fn pending_holding_update(&mut self, _fence: &Fence) -> Result<Option<HoldingUpdate>> {
        Ok(None)
    }
    /// Reconcile owner-authenticated controls against this newly observed plan.
    /// Production implementations preserve latches across executor restarts.
    fn synchronize_owner_controls(
        &mut self,
        _fence: &Fence,
        _config: &TradingConfig,
        _state: &TradingState,
        defaults: &OwnerControls,
        _now: DateTime<Utc>,
    ) -> Result<OwnerControls> {
        Ok(defaults.clone())
    }
    /// Resolve current persisted deployment authority immediately before a new
    /// live entry. The returned expiry also bounds the broker dispatch deadline.
    fn validate_entry_release(
        &mut self,
        _fence: &Fence,
        config: &TradingConfig,
        _now: DateTime<Utc>,
    ) -> Result<Option<DateTime<Utc>>> {
        require(
            config.mode != Mode::Live,
            "live entries require a persisted release resolver",
        )?;
        Ok(None)
    }
    fn release(&mut self, fence: &Fence) -> Result<()>;
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum OrderRole {
    Entry,
    Protection,
    Exit,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TrackedOrder {
    pub request: BrokerOrderRequest,
    pub role: OrderRole,
    pub attempted: bool,
    pub observation: Option<BrokerOrder>,
    pub cancellation_requested: bool,
    pub failure: Option<String>,
}
impl TrackedOrder {
    pub fn broker_id(&self) -> Option<&str> {
        self.observation
            .as_ref()
            .map(|o| o.broker_order_id.as_str())
    }
    fn terminal(&self) -> bool {
        self.observation
            .as_ref()
            .is_some_and(|o| o.status.terminal())
    }
    fn remaining(&self) -> Result<Decimal> {
        match &self.observation {
            Some(o) if !o.status.terminal() => sub(o.quantity, o.filled_quantity),
            _ => Ok(Decimal::ZERO),
        }
    }
}

