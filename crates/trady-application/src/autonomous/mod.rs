pub struct AutonomousTrader {
    pub config: TradingConfig,
    pub fence: Fence,
}

impl AutonomousTrader {
    pub fn start(
        config: TradingConfig,
        worker: WorkerId,
        journal: &mut impl ExecutionJournal,
        _clock: &impl Clock,
    ) -> Result<Self> {
        config.validate_for_management()?;
        let fence = journal.acquire(&config, &worker, 120)?;
        Ok(Self { config, fence })
    }

    pub fn cycle(
        &self,
        journal: &mut impl ExecutionJournal,
        broker: &mut impl ExecutionBroker,
        inputs: &mut impl TradingInputs,
        controls: &OwnerControls,
        clock: &impl Clock,
    ) -> Result<CycleReport> {
        // Expired release/capability evidence prevents new entry; existing protection still runs.
        journal.renew(&self.fence, 120)?;
        let mut state = journal.load(&self.fence)?;
        let observed = broker.observe(&self.config.account_id, &state.orders)?;
        let now = clock.now();
        observed.snapshot.validate()?;
        require(
            observed.snapshot.account_id == self.config.account_id
                && observed.snapshot.mode == self.config.mode
                && observed.snapshot.spendable_cash.currency == self.config.base_currency
                && fresh(observed.snapshot.observed_at, now, 60),
            "incompatible or stale execution observation",
        )?;
        require(
            observed.total_equity.currency == self.config.base_currency
                && observed.total_equity.amount >= Decimal::ZERO,
            "invalid account equity",
        )?;
        if state
            .last_snapshot
            .as_ref()
            .is_some_and(|old| old.observed_at > observed.snapshot.observed_at)
        {
            return Err(Error("broker observation regressed".into()));
        }
        if let Some(reason) = reconcile_orders(&mut state, &observed.snapshot)? {
            state.position_state = PositionState::RecoveryRequired;
            state.recovery_reason = Some(reason.clone());
            state.last_snapshot = Some(observed.snapshot);
            persist(journal, &self.fence, &mut state)?;
            return Ok(report(&state, "reconcile_required", Some(reason)));
        }
        state.recovery_reason = None;
        state.last_snapshot = Some(observed.snapshot.clone());
        let session = inputs
            .session(&self.config.account_id, now)
            .ok()
            .flatten()
            .filter(|s| s.validate(&self.config.base_currency, clock.now()).is_ok());
        let now = clock.now();
        if let Some(s) = &session {
            let performance = trady_policy::capital::session_performance(
                s.opening_equity.amount,
                observed.total_equity.amount,
                s.deposits.amount,
                s.withdrawals.amount,
            )?;
            if performance
                .loss_guard_fraction
                .is_some_and(|loss| loss <= Decimal::new(-2, 2))
            {
                state.loss_paused_sessions.insert(s.session_id.clone());
            }
        }
        persist(journal, &self.fence, &mut state)?;
        let controls = journal.synchronize_owner_controls(
            &self.fence,
            &self.config,
            &state,
            controls,
            clock.now(),
        )?;
        if state.plan.is_some() {
            return self.manage(
                journal,
                broker,
                inputs,
                &mut state,
                &observed,
                session.as_ref(),
                &controls,
                clock,
            );
        }
        state.position_state = PositionState::Flat;
        if controls.pause_entries || controls.close_position || self.config.mode == Mode::Shadow {
            return Ok(report(&state, "entry_paused", None));
        }
        self.config.validate(now)?;
        journal.validate_entry_release(&self.fence, &self.config, now)?;
        let Some(session) = session else {
            return Ok(report(
                &state,
                "no_entry",
                Some("verified exchange session/accounting unavailable".into()),
            ));
        };
        if !session.permits_entry(now)
            || state.consumed_sessions.contains(&session.session_id)
            || state.loss_paused_sessions.contains(&session.session_id)
        {
            return Ok(report(
                &state,
                "no_entry",
                Some("session entry window, loss pause or daily slot blocks entry".into()),
            ));
        }
        validate_account_entry(&observed.snapshot, &self.config.capabilities, now)?;
        let Some(candidate) = inputs.candidate(&observed.snapshot, now)? else {
            return Ok(report(&state, "no_candidate", None));
        };
        let quote = inputs.quote(&candidate.instrument_id)?;
        let now = clock.now();
        candidate.validate(&self.config, &observed.snapshot, &quote, now)?;
        let limits =
            candidate.authoritative_limits(&self.config, &observed.snapshot, &quote, now)?;
        let size = trady_policy::SizedEntry {
            limit_price: limits.buy_limit,
            quantity: limits.quantity,
            budget: limits.budget.clone(),
            estimated_cost: limits.acquisition_cost.clone(),
            remaining_cash: Money {
                amount: sub(
                    observed.snapshot.spendable_cash.amount,
                    limits.acquisition_cost.amount,
                )?,
                currency: self.config.base_currency.clone(),
            },
        };
        let proceeds_at_stop = candidate.net_proceeds(size.quantity, candidate.stop_price, now)?;
        let planned_loss = div(
            sub(size.estimated_cost.amount, proceeds_at_stop)?,
            size.estimated_cost.amount,
        )?;
        trady_policy::validate_risk(
            candidate.target_net_fraction,
            planned_loss,
            trady_policy::confidence(&candidate.confidence_inputs).total(),
            candidate.exceptional_verified,
            &self.config.policy,
        )?;
        require(
            candidate.stop_price < quote.bid,
            "entry stop must be below executable bid",
        )?;
        require(
            size.quantity.fract() == Decimal::ZERO
                || self.config.capabilities.fractional_orders.usable(now),
            "fractional orders lack current capability evidence",
        )?;
        if candidate.currency != self.config.base_currency {
            let current = inputs
                .current_exit_costs(&candidate.instrument_id, clock.now())?
                .ok_or_else(|| {
                    Error("current FX/exit economics are required before entry".into())
                })?;
            candidate.validate_refreshed_exit_costs(&current, clock.now())?;
        }
        // Re-read account and time after potentially slow research/inference, before consuming a slot.
        let latest = broker.observe(&self.config.account_id, &state.orders)?;
        let dispatch_now = clock.now();
        require(
            latest.snapshot.spendable_cash == observed.snapshot.spendable_cash
                && latest.snapshot.positions.is_empty()
                && latest.snapshot.orders.iter().all(|o| o.status.terminal())
                && fresh(latest.snapshot.observed_at, dispatch_now, 60)
                && session.permits_entry(dispatch_now),
            "account or session changed during research; reassess",
        )?;
        let dispatch_quote = inputs.quote(&candidate.instrument_id)?;
        let dispatch_now = clock.now();
        require(
            latest.snapshot.account_id == self.config.account_id
                && latest.snapshot.mode == self.config.mode,
            "final account observation changed identity",
        )?;
        self.config.validate(dispatch_now)?;
        let release_expiry =
            journal.validate_entry_release(&self.fence, &self.config, dispatch_now)?;
        validate_account_entry(&latest.snapshot, &self.config.capabilities, dispatch_now)?;
        require(
            session.permits_entry(dispatch_now),
            "exchange entry window ended during final quote read",
        )?;
        candidate.validate(
            &self.config,
            &observed.snapshot,
            &dispatch_quote,
            dispatch_now,
        )?;
        let mut expires_at = candidate
            .valid_until
            .min(candidate.advisor.valid_until)
            .min(session.closes_at - Duration::minutes(30))
            .min(dispatch_quote.observed_at + Duration::seconds(10))
            .min(dispatch_quote.received_at + Duration::seconds(10))
            .min(latest.snapshot.observed_at + Duration::seconds(60));
        for capability in [
            &self.config.capabilities.cash_account,
            &self.config.capabilities.instrument,
            &self.config.capabilities.protective_orders,
            &self.config.capabilities.quotes,
        ] {
            if let Some(expiry) = capability.valid_until {
                expires_at = expires_at.min(expiry);
            }
        }
        if size.quantity.fract() != Decimal::ZERO
            && let Some(expiry) = self.config.capabilities.fractional_orders.valid_until
        {
            expires_at = expires_at.min(expiry);
        }
        if let Some(release) = &self.config.live_release {
            expires_at = expires_at.min(release.valid_until);
        }
        if let Some(expiry) = release_expiry {
            expires_at = expires_at.min(expiry);
        }
        for record in &candidate.dossier.records {
            expires_at = expires_at.min(record.valid_until);
        }
        if let Some(predictions) = candidate
            .formula
            .as_ref()
            .and_then(|f| f.predictions.as_ref())
        {
            for prediction in &predictions.predictions {
                expires_at = expires_at.min(prediction.metadata.valid_until);
            }
        }
        state.consumed_sessions.insert(session.session_id.clone());
        let holding_state = trady_policy::holding::HoldingState::new(
            candidate.instrument_id.clone(),
            candidate.instrument_rules.price_tick,
            trady_policy::holding::HoldingPlan {
                version: 1,
                stop_price: candidate.stop_price,
                target_net_fraction: candidate.target_net_fraction,
                deadline: candidate.deadline_at,
                trailing: trady_policy::holding::TrailingSettings::default(),
            },
            &self.config.policy,
        )?;
        state.plan = Some(ActivePlan {
            candidate: candidate.clone(),
            acquired_quantity: Decimal::ZERO,
            entry_session: session.session_id.clone(),
            entry_session_close: session.closes_at,
            entered_at: dispatch_now,
            first_order: state.orders.len(),
            holding_state,
            holding_sessions: BTreeSet::from([session.session_id]),
            exit_latch: None,
            market_exit_required: false,
            data_unusable_since: None,
        });
        state.position_state = PositionState::EntryPending;
        let request = BrokerOrderRequest {
            intent_id: IntentId::new(crate::harness::new_id("entry"))?,
            account_id: self.config.account_id.clone(),
            instrument_id: candidate.instrument_id,
            instrument_currency: candidate.currency,
            side: Side::Buy,
            quantity: size.quantity,
            kind: OrderKind::Limit {
                price: size.limit_price,
                time_in_force: TimeInForce::Day,
            },
        };
        dispatch(
            journal,
            broker,
            &self.fence,
            &mut state,
            request,
            OrderRole::Entry,
            Some(expires_at),
        )?;
        Ok(report(&state, "entry_submitted", None))
    }

    #[allow(clippy::too_many_arguments)]
    fn manage(
        &self,
        journal: &mut impl ExecutionJournal,
        broker: &mut impl ExecutionBroker,
        inputs: &mut impl TradingInputs,
        state: &mut TradingState,
        observed: &ExecutionObservation,
        session: Option<&MarketSession>,
        controls: &OwnerControls,
        clock: &impl Clock,
    ) -> Result<CycleReport> {
        let now = clock.now();
        let instrument = state
            .plan
            .as_ref()
            .ok_or_else(|| Error("active plan required".into()))?
            .candidate
            .instrument_id
            .clone();
        let quantity = observed
            .snapshot
            .positions
            .iter()
            .find(|p| p.instrument_id == instrument)
            .map_or(Decimal::ZERO, |p| p.quantity);
        let active_entry = state
            .orders
            .iter()
            .position(|o| o.role == OrderRole::Entry && !o.terminal());
        if quantity == Decimal::ZERO {
            if let Some(index) = state
                .orders
                .iter()
                .position(|o| o.role != OrderRole::Entry && !o.terminal())
            {
                cancel(journal, broker, &self.fence, state, index)?;
                return Ok(report(state, "cancel_remaining_sell", None));
            }
            if let Some(index) = active_entry {
                let expired = state.plan.as_ref().is_some_and(|p| {
                    now >= p.candidate.valid_until
                        || now >= p.entry_session_close - Duration::minutes(30)
                });
                if controls.close_position || expired || session.is_none() {
                    cancel(journal, broker, &self.fence, state, index)?;
                }
                return Ok(report(state, "entry_pending", None));
            }
            state.position_state = PositionState::Closed;
            state.plan = None;
            // Terminal history stays durable for idempotency and restart reconciliation.
            persist(journal, &self.fence, state)?;
            return Ok(report(state, "position_closed", None));
        }
        let plan = state
            .plan
            .as_mut()
            .ok_or_else(|| Error("active plan required".into()))?;
        if state.orders.iter().skip(plan.first_order).any(|o| {
            o.role == OrderRole::Protection
                && o.observation
                    .as_ref()
                    .is_some_and(|row| row.status == OrderStatus::Rejected)
        }) {
            plan.exit_latch
                .get_or_insert_with(|| "protection_rejected".into());
            plan.market_exit_required = true;
        }
        if let Some(s) = session {
            plan.holding_sessions.insert(s.session_id.clone());
        }
        if now >= plan.candidate.deadline_at {
            plan.exit_latch
                .get_or_insert_with(|| "holding_deadline".into());
            plan.market_exit_required = true;
        }
        if session.is_some_and(|s| state.loss_paused_sessions.contains(&s.session_id)) {
            plan.exit_latch.get_or_insert_with(|| "session_loss".into());
            plan.market_exit_required = true;
        }
        if plan.holding_sessions.len() >= usize::from(plan.candidate.max_holding_sessions)
            && session.is_some_and(|s| s.closes_at - now <= Duration::minutes(5))
        {
            plan.exit_latch
                .get_or_insert_with(|| "holding_deadline".into());
        }
        if plan.candidate.max_holding_sessions == 1
            && now >= plan.entry_session_close - Duration::minutes(5)
        {
            plan.exit_latch
                .get_or_insert_with(|| "holding_deadline".into());
        }
        let quote = inputs.quote(&instrument).ok();
        let current_exit_costs = inputs
            .current_exit_costs(&instrument, clock.now())
            .ok()
            .flatten();
        let now = clock.now();
        let quote = quote.filter(|q| {
            q.instrument_id == instrument
                && q.currency == plan.candidate.currency
                && q.tradable
                && q.bid > Decimal::ZERO
                && q.ask >= q.bid
                && q.observed_at <= q.received_at
                && fresh(q.observed_at, now, 10)
                && fresh(q.received_at, now, 10)
        });
        let mut profit_limit = None;
        if let Some(q) = &quote {
            plan.data_unusable_since = None;
            if q.bid <= plan.candidate.stop_price {
                plan.exit_latch.get_or_insert_with(|| "stop_reached".into());
            }
            if let Some(cost) = observed
                .position_costs
                .get(&instrument)
                .filter(|c| c.currency == self.config.base_currency && c.amount > Decimal::ZERO)
            {
                let mut economics = plan.candidate.clone();
                if let Some(costs) = &current_exit_costs {
                    economics.exit_costs = costs.clone();
                }
                let basis = trady_policy::economics::CostBasis {
                    instrument_id: instrument.clone(),
                    quantity,
                    instrument_currency: plan.candidate.currency.clone(),
                    acquisition_cost: cost.clone(),
                };
                let protected = state
                    .orders
                    .iter()
                    .filter(|o| o.role == OrderRole::Protection && !o.terminal())
                    .try_fold(Decimal::ZERO, |sum, o| add(sum, o.remaining()?))?
                    >= quantity;
                let context = trady_policy::holding::HoldingContext {
                    now,
                    session: session.map(|s| trady_policy::holding::SessionWindow {
                        opens_at: s.opens_at,
                        closes_at: s.closes_at,
                    }),
                    holding_session_number: Some(
                        u32::try_from(plan.holding_sessions.len())
                            .map_err(|_| Error("holding session count overflow".into()))?,
                    ),
                    overnight_protection_verified: protected
                        && self.config.capabilities.protective_orders.usable(now),
                    research_available: false,
                    order_outcome_known: true,
                    owner_close_authenticated: controls.close_position,
                };
                let evaluation = trady_policy::holding::evaluate_holding(
                    &plan.holding_state,
                    &basis,
                    Some(q),
                    &economics.liquidation_costs(),
                    &context,
                    &self.config.policy,
                )?;
                plan.holding_state = evaluation.state;
                if let Some(latch) = plan.holding_state.exit_latch() {
                    plan.exit_latch
                        .get_or_insert_with(|| format!("{:?}", latch.reason));
                }
                if plan.exit_latch.is_none()
                    && let Some(update) = journal.pending_holding_update(&self.fence).ok().flatten()
                    && let Ok(activation) = activate_reviewed_holding_update(
                        &self.config,
                        plan,
                        &update,
                        &basis,
                        q,
                        &economics.liquidation_costs(),
                        &context,
                    )
                {
                    plan.holding_state = activation.evaluation.state;
                    if activation.activated {
                        plan.candidate.target_net_fraction =
                            plan.holding_state.plan().target_net_fraction;
                        plan.candidate.deadline_at = plan.holding_state.plan().deadline;
                        plan.candidate.sentiment_reference =
                            update.research.sentiment_reference.clone();
                    }
                    if let Some(latch) = plan.holding_state.exit_latch() {
                        plan.exit_latch
                            .get_or_insert_with(|| format!("{:?}", latch.reason));
                    }
                }
                if let Ok(proceeds) = economics.net_proceeds(quantity, q.bid, now) {
                    let net_return = div(sub(proceeds, cost.amount)?, cost.amount)?;
                    if net_return >= plan.candidate.target_net_fraction {
                        plan.exit_latch
                            .get_or_insert_with(|| "net_target_reached".into());
                    }
                    if let Some(reason) = &plan.exit_latch {
                        let profit_exit =
                            reason == "net_target_reached" || reason == "ProfitTarget";
                        if profit_exit && !plan.market_exit_required {
                            let price = trady_policy::economics::target_price(
                                &basis,
                                plan.candidate.target_net_fraction,
                                &economics.liquidation_costs(),
                                plan.candidate.instrument_rules.price_tick,
                                now,
                            )?;
                            if q.bid >= price {
                                profit_limit = Some(price);
                            } else {
                                plan.market_exit_required = true;
                            }
                        }
                    }
                } else {
                    plan.exit_latch
                        .get_or_insert_with(|| "exit_economics_unavailable".into());
                }
            } else {
                plan.exit_latch
                    .get_or_insert_with(|| "actual_cost_basis_unavailable".into());
            }
        } else {
            let since = *plan.data_unusable_since.get_or_insert(now);
            if now - since >= Duration::seconds(60) {
                plan.exit_latch
                    .get_or_insert_with(|| "market_data_degraded".into());
            }
        }
        if controls.close_position {
            plan.exit_latch.get_or_insert_with(|| "owner_close".into());
            plan.market_exit_required = true;
        }
        if !self.config.capabilities.protective_orders.usable(now) {
            plan.exit_latch
                .get_or_insert_with(|| "protection_evidence_expired".into());
            plan.market_exit_required = true;
        }
        if plan.market_exit_required {
            profit_limit = None;
        }
        let exiting = plan.exit_latch.is_some();
        state.position_state = if exiting {
            PositionState::ExitLatched
        } else {
            PositionState::OpenUnprotected
        };
        persist(journal, &self.fence, state)?;
        if !exiting && let Some(costs) = &current_exit_costs {
            journal.record_holding_observation(&self.fence, observed, costs)?;
        }
        // Stop any remaining entry before a liquidation can race with further buys.
        if let Some(index) = active_entry {
            cancel(journal, broker, &self.fence, state, index)?;
            if exiting {
                return Ok(report(state, "cancel_entry_before_exit", None));
            }
        }
        if exiting {
            // Preserve native protection until software liquidation has an
            // executable market. The durable exit latch survives any outage.
            if quote.is_none() || session.is_none() {
                return Ok(report(state, "exit_waiting_for_tradable_market", None));
            }
            if let Some(index) = state
                .orders
                .iter()
                .position(|o| o.role == OrderRole::Protection && !o.terminal())
            {
                cancel(journal, broker, &self.fence, state, index)?;
                return Ok(report(state, "cancel_protection_before_exit", None));
            }
            if let Some(index) = state
                .orders
                .iter()
                .position(|o| o.role == OrderRole::Exit && !o.terminal())
            {
                if profit_limit.is_none()
                    && matches!(state.orders[index].request.kind, OrderKind::Limit { .. })
                {
                    cancel(journal, broker, &self.fence, state, index)?;
                    return Ok(report(state, "cancel_target_before_market_exit", None));
                }
                state.position_state = PositionState::ExitPending;
                persist(journal, &self.fence, state)?;
                return Ok(report(state, "exit_pending", None));
            }
            let available = observed
                .available_quantities
                .get(&instrument)
                .copied()
                .unwrap_or(Decimal::ZERO);
            require(
                available >= quantity,
                "reconcile reserved stock before exit",
            )?;
            let candidate = &state
                .plan
                .as_ref()
                .ok_or_else(|| Error("active plan required".into()))?
                .candidate;
            let kind = profit_limit.map_or(
                OrderKind::Market {
                    extended_hours: false,
                },
                |price| OrderKind::Limit {
                    price,
                    time_in_force: TimeInForce::Day,
                },
            );
            let request = BrokerOrderRequest {
                intent_id: IntentId::new(crate::harness::new_id("exit"))?,
                account_id: self.config.account_id.clone(),
                instrument_id: instrument,
                instrument_currency: candidate.currency.clone(),
                side: Side::Sell,
                quantity,
                kind,
            };
            state.position_state = PositionState::ExitPending;
            dispatch(
                journal,
                broker,
                &self.fence,
                state,
                request,
                OrderRole::Exit,
                None,
            )?;
            return Ok(report(state, "exit_submitted", None));
        }
        let reserved = state
            .orders
            .iter()
            .filter(|o| o.role == OrderRole::Protection && !o.terminal())
            .try_fold(Decimal::ZERO, |sum, o| add(sum, o.remaining()?))?;
        require(
            reserved <= quantity,
            "protective orders exceed remaining holding",
        )?;
        if reserved < quantity {
            let uncovered = sub(quantity, reserved)?;
            let available = observed
                .available_quantities
                .get(&instrument)
                .copied()
                .unwrap_or(Decimal::ZERO);
            require(
                available >= uncovered,
                "available quantity cannot cover protection",
            )?;
            let candidate = &state
                .plan
                .as_ref()
                .ok_or_else(|| Error("active plan required".into()))?
                .candidate;
            let request = BrokerOrderRequest {
                intent_id: IntentId::new(crate::harness::new_id("protect"))?,
                account_id: self.config.account_id.clone(),
                instrument_id: instrument,
                instrument_currency: candidate.currency.clone(),
                side: Side::Sell,
                quantity: uncovered,
                kind: OrderKind::Stop {
                    price: candidate.stop_price,
                    time_in_force: TimeInForce::GoodTillCancel,
                },
            };
            dispatch(
                journal,
                broker,
                &self.fence,
                state,
                request,
                OrderRole::Protection,
                None,
            )?;
            if state.orders.last().is_some_and(|o| {
                o.observation
                    .as_ref()
                    .is_some_and(|o| o.status == OrderStatus::Rejected)
            }) {
                state
                    .plan
                    .as_mut()
                    .ok_or_else(|| Error("active plan required".into()))?
                    .exit_latch
                    .get_or_insert_with(|| "protection_rejected".into());
                persist(journal, &self.fence, state)?;
            }
            return Ok(report(state, "protection_submitted", None));
        }
        state.position_state = PositionState::OpenProtected;
        persist(journal, &self.fence, state)?;
        Ok(report(state, "holding_protected", None))
    }
}

fn report(state: &TradingState, action: &str, reason: Option<String>) -> CycleReport {
    CycleReport {
        revision: state.revision,
        state: state.position_state,
        action: action.into(),
        reason,
    }
}

fn persist(
    journal: &mut impl ExecutionJournal,
    fence: &Fence,
    state: &mut TradingState,
) -> Result<()> {
    let previous = state.revision;
    state.revision = previous
        .checked_add(1)
        .ok_or_else(|| Error("journal revision exhausted".into()))?;
    journal.save(fence, previous, state)
}

fn reconcile_orders(
    state: &mut TradingState,
    snapshot: &AccountSnapshot,
) -> Result<Option<String>> {
    if snapshot.positions.len() > 1 {
        return Ok(Some("multiple holdings require recovery".into()));
    }
    let mut known = BTreeSet::new();
    for tracked in &mut state.orders {
        if !tracked.attempted {
            return Ok(Some(
                "prepared intent requires explicit recovery; never auto-resubmit".into(),
            ));
        }
        let Some(id) = tracked.broker_id().map(str::to_owned) else {
            return Ok(Some(
                "submission outcome unknown; bind an exact broker ID through reviewed recovery"
                    .into(),
            ));
        };
        if !known.insert(id.clone()) {
            return Ok(Some("duplicate broker order binding".into()));
        }
        let row = snapshot.orders.iter().find(|o| o.broker_order_id == id);
        // Terminal observations are durable facts; a missing pending row cannot erase them.
        if tracked.terminal() && row.is_none() {
            continue;
        }
        let Some(order) = row else {
            return Ok(Some(format!(
                "broker order {id} missing from pending/history"
            )));
        };
        if order.instrument_id != tracked.request.instrument_id
            || order.side != tracked.request.side
            || order.quantity != tracked.request.quantity
            || order.status == OrderStatus::Unknown
            || tracked.observation.as_ref().is_some_and(|old| {
                order.filled_quantity < old.filled_quantity
                    || (old.status.terminal() && old != order)
            })
        {
            return Ok(Some(format!("inconsistent broker order {id}")));
        }
        tracked.observation = Some(order.clone());
    }
    if snapshot
        .orders
        .iter()
        .any(|o| !o.status.terminal() && !known.contains(&o.broker_order_id))
    {
        return Ok(Some("untracked broker order requires recovery".into()));
    }
    if let Some(plan) = &mut state.plan {
        let instrument = &plan.candidate.instrument_id;
        if snapshot
            .positions
            .iter()
            .any(|p| &p.instrument_id != instrument)
        {
            return Ok(Some("holding differs from active plan".into()));
        }
        let mut acquired = Decimal::ZERO;
        let mut sold = Decimal::ZERO;
        require(
            plan.first_order <= state.orders.len(),
            "invalid plan order boundary",
        )?;
        for o in state
            .orders
            .iter()
            .skip(plan.first_order)
            .filter(|o| o.request.instrument_id == *instrument)
        {
            if let Some(row) = &o.observation {
                if o.role == OrderRole::Entry {
                    acquired = add(acquired, row.filled_quantity)?;
                } else {
                    sold = add(sold, row.filled_quantity)?;
                }
            }
        }
        let expected = sub(acquired, sold)?;
        let actual = snapshot
            .positions
            .first()
            .map_or(Decimal::ZERO, |p| p.quantity);
        if expected != actual || expected < Decimal::ZERO {
            return Ok(Some("filled orders disagree with actual holding; corporate action/manual change requires recovery".into()));
        }
        plan.acquired_quantity = acquired;
    } else if !snapshot.positions.is_empty() {
        return Ok(Some("unexplained broker holding".into()));
    }
    Ok(None)
}

fn dispatch(
    journal: &mut impl ExecutionJournal,
    broker: &mut impl ExecutionBroker,
    fence: &Fence,
    state: &mut TradingState,
    request: BrokerOrderRequest,
    role: OrderRole,
    expires_at: Option<DateTime<Utc>>,
) -> Result<()> {
    request.validate().map_err(|e| Error(e.to_string()))?;
    state.orders.push(TrackedOrder {
        request: request.clone(),
        role,
        attempted: false,
        observation: None,
        cancellation_requested: false,
        failure: None,
    });
    persist(journal, fence, state)?;
    let index = state.orders.len() - 1;
    // A crash from this point is ambiguous, including a crash immediately before send.
    state.orders[index].attempted = true;
    persist(journal, fence, state)?;
    journal.renew(fence, 120)?;
    let submission = if let Some(deadline) = expires_at {
        broker.submit_order_before(&request, deadline)
    } else {
        broker.submit_order(&request)
    };
    match submission {
        Ok(order)
            if order.instrument_id == request.instrument_id
                && order.side == request.side
                && order.quantity == request.quantity
                && order.status != OrderStatus::Unknown =>
        {
            state.orders[index].observation = Some(order);
        }
        Ok(_) => {
            state.orders[index].failure = Some("incompatible broker acknowledgment".into());
            state.position_state = PositionState::RecoveryRequired;
        }
        Err(error) => {
            state.orders[index].failure = Some(error.to_string());
            if !error.outcome_unknown {
                // Definitive no-send/rejection is terminal locally; its ID is explicitly local.
                state.orders[index].observation = Some(BrokerOrder {
                    broker_order_id: format!("local_{}", request.intent_id),
                    client_intent_id: Some(request.intent_id),
                    instrument_id: request.instrument_id,
                    side: request.side,
                    quantity: request.quantity,
                    filled_quantity: Decimal::ZERO,
                    status: OrderStatus::Rejected,
                });
            } else if let Some(id) = error.broker_order_id {
                state.orders[index].observation = Some(BrokerOrder {
                    broker_order_id: id,
                    client_intent_id: Some(request.intent_id),
                    instrument_id: request.instrument_id,
                    side: request.side,
                    quantity: request.quantity,
                    filled_quantity: Decimal::ZERO,
                    status: OrderStatus::Unknown,
                });
            }
            state.position_state = if error.outcome_unknown {
                PositionState::RecoveryRequired
            } else {
                state.position_state
            };
        }
    }
    persist(journal, fence, state)
}

fn cancel(
    journal: &mut impl ExecutionJournal,
    broker: &mut impl ExecutionBroker,
    fence: &Fence,
    state: &mut TradingState,
    index: usize,
) -> Result<()> {
    if state.orders[index].cancellation_requested {
        return Ok(());
    }
    let id = state.orders[index]
        .broker_id()
        .ok_or_else(|| Error("cannot cancel order with unknown broker ID".into()))?
        .to_owned();
    state.orders[index].cancellation_requested = true;
    persist(journal, fence, state)?;
    journal.renew(fence, 120)?;
    if let Err(error) = broker.cancel_order(&fence.account_id, &id) {
        state.orders[index].failure = Some(error.to_string());
        // A definitive no-send response permits a new cancellation attempt after
        // the next account reconciliation. An ambiguous cancellation stays pending.
        if !error.outcome_unknown {
            state.orders[index].cancellation_requested = false;
        }
    }
    // A cancellation acknowledgment never changes terminal state or available quantity.
    persist(journal, fence, state)
}

/// Trusted owner recovery operation. Bind one ambiguous intent to a reviewed exact
/// broker ID only after the broker independently returns matching order facts.
pub fn recover_order(
    journal: &mut impl ExecutionJournal,
    broker: &mut impl ExecutionBroker,
    fence: &Fence,
    intent: &IntentId,
    broker_id: &str,
    clock: &impl Clock,
) -> Result<CycleReport> {
    require(
        !broker_id.is_empty()
            && broker_id.len() <= 128
            && broker_id
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'_'),
        "invalid recovery broker order ID",
    )?;
    journal.renew(fence, 120)?;
    let mut state = journal.load(fence)?;
    require(
        !state
            .orders
            .iter()
            .any(|o| o.broker_id() == Some(broker_id)),
        "broker order already belongs to an intent",
    )?;
    let index = state
        .orders
        .iter()
        .position(|o| &o.request.intent_id == intent)
        .ok_or_else(|| Error("recovery intent does not exist".into()))?;
    let tracked = &mut state.orders[index];
    require(
        tracked.broker_id().is_none() && tracked.attempted,
        "only an ambiguous dispatched intent can be rebound",
    )?;
    tracked.observation = Some(BrokerOrder {
        broker_order_id: broker_id.into(),
        client_intent_id: Some(intent.clone()),
        instrument_id: tracked.request.instrument_id.clone(),
        side: tracked.request.side,
        quantity: tracked.request.quantity,
        filled_quantity: Decimal::ZERO,
        status: OrderStatus::Unknown,
    });
    let observation = broker.observe(&fence.account_id, &state.orders)?;
    observation.snapshot.validate()?;
    require(
        observation.snapshot.account_id == fence.account_id
            && fresh(observation.snapshot.observed_at, clock.now(), 60),
        "recovery observation scope or time mismatch",
    )?;
    let previous = state
        .last_snapshot
        .as_ref()
        .ok_or_else(|| Error("recovery requires the original account binding".into()))?;
    require(
        observation.snapshot.mode == previous.mode
            && observation.snapshot.spendable_cash.currency == previous.spendable_cash.currency
            && observation.snapshot.observed_at >= previous.observed_at,
        "recovery observation changed mode, currency or regressed in time",
    )?;
    let found = observation
        .snapshot
        .orders
        .iter()
        .find(|o| o.broker_order_id == broker_id)
        .ok_or_else(|| Error("exact recovery order is absent from pending/history".into()))?;
    let request = &state.orders[index].request;
    require(
        found.instrument_id == request.instrument_id
            && found.side == request.side
            && found.quantity == request.quantity
            && found.status != OrderStatus::Unknown,
        "recovery order is incompatible with the persisted intent",
    )?;
    state.orders[index].observation = Some(found.clone());
    state.orders[index].failure = None;
    let reason = reconcile_orders(&mut state, &observation.snapshot)?;
    state.position_state = if reason.is_some() {
        PositionState::RecoveryRequired
    } else if state.plan.is_some() {
        PositionState::OpenUnprotected
    } else {
        PositionState::Flat
    };
    state.recovery_reason = reason.clone();
    state.last_snapshot = Some(observation.snapshot);
    persist(journal, fence, &mut state)?;
    Ok(report(&state, "exact_order_recovered", reason))
}
