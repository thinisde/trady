#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TradingConfig {
    pub config_version: u32,
    pub account_id: AccountId,
    pub mode: Mode,
    pub base_currency: Currency,
    pub owner_id: String,
    pub policy: Policy,
    pub capabilities: Capabilities,
    /// Exact approved skill name -> content hash. Model-supplied skills confer no authority.
    pub approved_skills: BTreeMap<String, String>,
    pub live_release: Option<LiveRelease>,
    /// Missing authority pauses new entries. Open plans retain their original formula.
    #[serde(default)]
    pub limits_authority: Option<crate::optimization::FormulaAuthority>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LiveRelease {
    pub account_id: AccountId,
    pub policy_version: u32,
    pub valid_until: DateTime<Utc>,
    /// Deployment-owned evidence for each release gate, never generated by a model.
    pub gates: BTreeMap<String, String>,
}

impl TradingConfig {
    pub fn validate(&self, now: DateTime<Utc>) -> Result<()> {
        self.validate_for_management()?;
        require(
            self.mode != Mode::Live
                || self
                    .live_release
                    .as_ref()
                    .is_some_and(|r| r.valid_until > now),
            "live release expired; new entries are blocked",
        )
    }

    /// An expired release blocks new entries while permitting restart, exact
    /// recovery and risk-reducing management of the already bound account.
    pub fn validate_for_management(&self) -> Result<()> {
        self.policy.validate()?;
        require(
            self.config_version == 1 && !self.owner_id.is_empty(),
            "invalid trading configuration",
        )?;
        require(
            match self.mode {
                Mode::Paper => self.account_id.as_str().starts_with("paper_"),
                Mode::Live => self.account_id.as_str().starts_with("live_"),
                Mode::Shadow => self.account_id.as_str().starts_with("shadow_"),
            },
            "trading account/mode mismatch",
        )?;
        require(
            self.approved_skills
                .values()
                .all(|h| h.len() == 64 && h.bytes().all(|b| b.is_ascii_hexdigit())),
            "invalid approved skill hash",
        )?;
        if self.mode == Mode::Live {
            let release = self
                .live_release
                .as_ref()
                .ok_or_else(|| Error("live release evidence required".into()))?;
            require(
                release.account_id == self.account_id
                    && release.policy_version == self.policy.version,
                "incompatible live release",
            )?;
            for gate in [
                "account_binding",
                "broker_capabilities",
                "protection_recovery",
                "paper_acceptance",
                "shadow_acceptance",
                "costs_and_market_data",
                "model_validation",
                "owner_approval",
            ] {
                require(
                    release.gates.get(gate).is_some_and(|v| !v.is_empty()),
                    "incomplete live release evidence",
                )?;
            }
        }
        Ok(())
    }
}

